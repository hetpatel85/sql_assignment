"""Q6. Temperature Tracker"""

temps = [32, 35, 38, 41, 36, 29, 40]
days = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]

# Days above 37
print("Heat alert days:")
for i in range(len(temps)):
    if temps[i] > 37:
        print(days[i], "-", temps[i])

# Hottest day
hottest = max(temps)
position = temps.index(hottest)
print("Hottest day:", days[position], "with", hottest)

# Convert to Fahrenheit
fahrenheit = []
for t in temps:
    fahrenheit.append(t * 9 / 5 + 32)
print("Temperatures in Fahrenheit:", fahrenheit)

"""Q7. Word Frequency in a Sentence"""

sentence = input("Enter a sentence: ")
words = sentence.split()        # split into list of words

longest = words[0]
shortest = words[0]
capital_count = 0

for word in words:
    if len(word) > len(longest):
        longest = word
    if len(word) < len(shortest):
        shortest = word
    if word[0].isupper():
        capital_count = capital_count + 1

print("Longest word:", longest)
print("Shortest word:", shortest)
print("Words starting with capital letter:", capital_count)

"""Q8. Remove Negative Balances"""

balances = [1500, -200, 3000, -50, 0, 750, -1000]

positive_accounts = []
negative_accounts = []
total_owed = 0

for b in balances:
    if b > 0:
        positive_accounts.append(b)
    elif b < 0:
        negative_accounts.append(b)
        total_owed = total_owed + abs(b)    # abs() removes minus sign

print("Positive accounts:", positive_accounts)
print("Negative accounts:", negative_accounts)
print("Total amount owed:", total_owed)

"""Q9. Password Strength Checker"""

password = input("Enter password: ")

has_upper = False
has_lower = False
has_digit = False

for ch in password:
    if ch.isupper():
        has_upper = True
    elif ch.islower():
        has_lower = True
    elif ch.isdigit():
        has_digit = True

# Count how many conditions are met
score = 0
if has_upper:
    score = score + 1
if has_lower:
    score = score + 1
if has_digit:
    score = score + 1
if len(password) >= 8:
    score = score + 1

if score == 4:
    print("Strong")
elif score == 2 or score == 3:
    print("Medium")
else:
    print("Weak")

