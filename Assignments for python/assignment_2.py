"""Q4. Vowel Counter for a Tweet"""

text = input("Enter a sentence: ")

vowels = 0
consonants = 0
spaces = 0

for ch in text:
    if " " in ch:                     # is it a space?
        spaces += 1
    elif ch.isalpha()  :                    # is it a letter?
        if ch.lower() in "aeiou":                  # is it a vowel? (use lower())
            vowels += 1
        else:
            consonants += 1

print("Vowels:", vowels)
print("Consonants:", consonants)
print("Spaces:", spaces)

