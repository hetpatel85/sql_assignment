"""Q5. Character Counter"""

text = input("Enter text: ")

count = {}      # character -> how many times it appears

for ch in text:
    if ch != " ":                           # ignore spaces
        count[ch] = count.get(ch, 0) + 1    # get() returns 0 if ch is new
print(count)

# Find the most frequent character
best_char = ""
best_count = 0
for ch, c in count.items():
    if c > best_count:
        best_count = c
        best_char = ch
print("Most frequent character:", best_char, "(" + str(best_count), "times)")

"""Q6. Restaurant Menu Billing"""

