contacts = {}       # empty dictionary: name -> phone number

while True:
    print("\n1. Add contact")
    print("2. Search contact")
    print("3. Show all contacts")
    print("4. Exit")
    choice = input("Enter your choice: ")

    if choice == "1":
        name = input("Enter name: ")
        if name in contacts:                # name already a key
            print("Contact already exists")
        else:
            phone = input("Enter phone number: ")
            contacts[name] = phone          # add new key-value pair
            print("Contact added")

    elif choice == "2":
        name = input("Enter name to search: ")
        if name in contacts:
            print(name, ":", contacts[name])
        else:
            print("Contact not found")

    elif choice == "3":
        if len(contacts) == 0:
            print("No contacts yet")
        else:
            for name, phone in contacts.items():    # items() gives key and value
                print(name, ":", phone)

    elif choice == "4":
        print("Bye!")
        break                               # leave the menu loop

    else:
        print("Invalid choice")

