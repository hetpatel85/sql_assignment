"""Q9. Group Employees by Department"""

employees = [("Ravi", "IT"), ("Anjali", "HR"), ("Suresh", "IT"),
             ("Meena", "Finance"), ("Arun", "HR"), ("Divya", "IT")]

departments = {}

for name, dept in employees:
    if dept not in departments:
        departments[dept] = []              # new department: empty list
    departments[dept].append(name)          # add employee to that list

print(departments)

# Number of employees in each department
for dept, names in departments.items():
    print(dept, ":", len(names), "employees")

